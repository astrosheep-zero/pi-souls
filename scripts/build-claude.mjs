import { builtinModules } from "node:module";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
// The public SDK barrel has host side effects. Resolve its installed entry, then
// bundle only the upstream parser and its YAML dependency. A moved utility fails
// the build, never a standalone installation; no parser is copied into this repo.
const frontmatter = fileURLToPath(new URL("./utils/frontmatter.js", import.meta.resolve("@earendil-works/pi-coding-agent")));
const banner = { js: "// Generated by npm run build:claude; do not edit." };
const helper = await build({
  absWorkingDir: root,
  entryPoints: ["src/claude-souls-runner.ts"],
  outfile: "plugins/claude/hooks/souls-runner.cjs",
  bundle: true,
  platform: "node",
  format: "cjs",
  target: "node22.18",
  minify: true,
  banner,
  alias: { "@earendil-works/pi-coding-agent": frontmatter },
  metafile: true,
});
const dependencies = Object.values(helper.metafile.outputs).flatMap((output) => output.imports);
if (dependencies.some(({ path }) => !builtinModules.includes(path) && !builtinModules.includes(path.replace(/^node:/, "")))) {
  throw new Error("Soul helper has an unbundled runtime dependency");
}
await build({
  absWorkingDir: root,
  entryPoints: ["plugins/claude/hooks/register.ts"],
  outfile: "plugins/claude/hooks/register.js",
  bundle: true,
  platform: "neutral",
  format: "esm",
  target: "es2023",
  banner,
});
